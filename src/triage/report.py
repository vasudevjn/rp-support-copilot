"""Write the README results section from output files. No number in the README is typed by hand.

Run:  python -m triage.report
"""
from __future__ import annotations

import json
import re

import pandas as pd

from .config import OUTPUTS, ROOT

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def build() -> str:
    df = pd.read_csv(OUTPUTS / "triage_results.csv", keep_default_na=False)
    meta = json.loads((OUTPUTS / "run_metadata.json").read_text(encoding="utf-8"))
    safety = json.loads((OUTPUTS / "safety_checks.json").read_text(encoding="utf-8"))
    n = len(df)
    safe_auto = int(((df.action == "auto_resolve") & (df.send_mode == "auto_send")).sum())
    lines = [f"_Generated by `python -m triage.report` from `outputs/` (run {meta['run_at_utc']}, config "
             f"{meta['config_version']}, extraction sources {meta['extraction_sources']}, reply sources "
             f"{meta['reply_sources']})._", ""]
    lines += ["| Measure | Value |", "|---|---|", f"| Tickets triaged | {n} |"]
    for a in ["auto_resolve", "ask_info", "escalate"]:
        k = int((df.action == a).sum())
        lines.append(f"| Action: {a} | {k} ({k / n:.0%}) |")
    lines += [f"| Safe auto-resolve (auto_resolve and auto_send) | {safe_auto} ({safe_auto / n:.0%}) |",
              f"| Threat tickets escalated / marked do_not_send | {safety['threat_tickets'] - safety['threats_not_escalated']}"
              f" / {safety['threat_tickets'] - safety['threats_not_do_not_send']} of {safety['threat_tickets']} |",
              f"| Replies blocked by guardrails (FAIL_NEEDS_HUMAN) | {safety['guardrail_fail_needs_human']} |",
              f"| Replies passed after one regeneration | {safety['guardrail_pass_after_retry']} |",
              f"| Escalations set to auto_send | {safety['escalations_auto_sent']} |", ""]
    esc = df[df.action == "escalate"].escalation_team.value_counts()
    lines += ["**Escalations by team:** " + ", ".join(f"{t} {c}" for t, c in esc.items()), ""]
    sm = df.send_mode.value_counts()
    lines += ["**Send mode:** " + ", ".join(f"{t} {c}" for t, c in sm.items()), ""]
    ev = OUTPUTS / "eval_results.json"
    if ev.exists():
        r = json.loads(ev.read_text(encoding="utf-8"))
        lines += ["**Evaluation** (`python -m triage.evaluate`): spec cases are the expected outcomes written in "
                  "the spec before the build (`eval/spec_cases.yaml`); they cover the risky paths on purpose and "
                  "are not a random-sample accuracy estimate.", "",
                  "| Metric | Value |", "|---|---|",
                  f"| Spec cases fully passed | {r['spec_cases_all_pass']} / {r['spec_cases']} |",
                  f"| Spec checks passed | {r['spec_checks_passed']} / {r['spec_checks']} |",
                  f"| Action / team / category / risk checks | {r['action_checks_passed']} / "
                  f"{r['team_checks_passed']} / {r['category_checks_passed']} / {r['risk_checks_passed']} |",
                  f"| Reply content checks | {r['reply_checks_passed']} |",
                  f"| Critical errors over all {r['n_tickets']} tickets | {r['critical_errors']} |"]
    else:
        lines += ["**Evaluation:** not run yet (`python -m triage.evaluate`)."]
    return "\n".join(lines)


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    block = f"{START}\n{build()}\n{END}"
    text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    readme.write_text(text, encoding="utf-8")
    print("README results section updated.")


if __name__ == "__main__":
    main()
